package com.ilearn.app.youtube

import kotlinx.coroutines.CoroutineStart
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.awaitCancellation
import kotlinx.coroutines.coroutineScope
import kotlinx.coroutines.ensureActive
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.net.URI
import java.util.Locale
import java.util.concurrent.TimeUnit

data class YouTubeCaptionTrack(
    val languageCode: String,
    val name: String,
    val baseUrl: String,
    val isAutoGenerated: Boolean
)

/**
 * Fetches public YouTube caption tracks via Innertube player metadata and converts them into
 * clean timestamped WebVTT so they plug directly into [com.ilearn.app.tutor.TranscriptParser].
 */
class YouTubeTranscriptClient(baseClient: OkHttpClient = sharedClient) {
    private val client = baseClient.newBuilder()
        .followRedirects(false)
        .followSslRedirects(false)
        .retryOnConnectionFailure(false)
        .connectTimeout(20, TimeUnit.SECONDS)
        .readTimeout(30, TimeUnit.SECONDS)
        .callTimeout(45, TimeUnit.SECONDS)
        .build()

    suspend fun fetchTracks(videoId: String): List<YouTubeCaptionTrack> = withContext(Dispatchers.IO) {
        require(videoId.matches(Regex("[A-Za-z0-9_-]{11}"))) { "Invalid YouTube video ID" }
        val html = executeGet(
            url = "https://www.youtube.com/watch?v=$videoId",
            userAgent = DESKTOP_UA,
            acceptLanguage = "en-US,en;q=0.9,ar;q=0.8",
            maxBytes = 4_000_000
        )
        val innertubeKey = extractInnertubeApiKey(html)
            ?: error("Unable to read YouTube player configuration")

        val androidTracks = fetchPlayerTracks(
            innertubeKey = innertubeKey,
            videoId = videoId,
            clientName = "ANDROID",
            clientVersion = "20.10.38",
            userAgent = ANDROID_UA
        )
        if (androidTracks.isNotEmpty()) return@withContext androidTracks

        fetchPlayerTracks(
            innertubeKey = innertubeKey,
            videoId = videoId,
            clientName = "IOS",
            clientVersion = "20.10.4",
            userAgent = IOS_UA
        )
    }

    suspend fun downloadAsVtt(track: YouTubeCaptionTrack): String = withContext(Dispatchers.IO) {
        validateTrackUrl(track.baseUrl)
        val json3Url = setFormatParam(track.baseUrl, "json3")
        val json3Body = runCatching {
            executeGet(json3Url, userAgent = ANDROID_UA, maxBytes = 4_000_000)
        }.getOrDefault("")
        if (json3Body.isNotBlank()) {
            val vtt = runCatching { json3ToVtt(json3Body) }.getOrDefault("")
            if (vtt.isNotBlank()) return@withContext vtt
        }

        val vttUrl = setFormatParam(track.baseUrl, "vtt")
        val rawVtt = executeGet(vttUrl, userAgent = ANDROID_UA, maxBytes = 2_000_000)
        val cleaned = cleanWebVtt(rawVtt)
        require(cleaned.isNotBlank()) { "Downloaded caption track is empty" }
        cleaned
    }

    private suspend fun fetchPlayerTracks(
        innertubeKey: String,
        videoId: String,
        clientName: String,
        clientVersion: String,
        userAgent: String
    ): List<YouTubeCaptionTrack> {
        val body = JSONObject()
            .put("context", JSONObject().put("client", JSONObject()
                .put("clientName", clientName)
                .put("clientVersion", clientVersion)))
            .put("videoId", videoId)
            .toString()
        val request = Request.Builder()
            .url("https://www.youtube.com/youtubei/v1/player?key=$innertubeKey")
            .post(body.toRequestBody("application/json".toMediaType()))
            .header("User-Agent", userAgent)
            .build()
        val responseText = executeCall(request, maxBytes = 3_000_000)
        return parseCaptionTracks(responseText)
    }

    private suspend fun executeGet(
        url: String,
        userAgent: String,
        acceptLanguage: String? = null,
        maxBytes: Int
    ): String {
        val builder = Request.Builder().url(url).header("User-Agent", userAgent)
        if (!acceptLanguage.isNullOrBlank()) builder.header("Accept-Language", acceptLanguage)
        return executeCall(builder.build(), maxBytes)
    }

    private suspend fun executeCall(request: Request, maxBytes: Int): String = coroutineScope {
        val call = client.newCall(request)
        val guard = launch(start = CoroutineStart.UNDISPATCHED) {
            try {
                awaitCancellation()
            } finally {
                call.cancel()
            }
        }
        try {
            call.execute().use { response ->
                check(response.isSuccessful) { "YouTube caption request failed (HTTP ${response.code})" }
                val source = response.body?.source() ?: error("Empty YouTube caption response")
                val buffer = okio.Buffer()
                var total = 0L
                while (!source.exhausted()) {
                    ensureActive()
                    val read = source.read(buffer, 8192)
                    if (read < 0) break
                    total += read
                    require(total <= maxBytes) { "YouTube caption response exceeded safety limit" }
                }
                buffer.readUtf8()
            }
        } finally {
            guard.cancel()
        }
    }

    companion object {
        private val sharedClient = OkHttpClient()
        private const val DESKTOP_UA =
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"
        private const val ANDROID_UA = "com.google.android.youtube/20.10.38 (Linux; U; Android 14)"
        private const val IOS_UA = "com.google.ios.youtube/20.10.4 (iPhone16,2; U; CPU iOS 17_5 like Mac OS X)"
        private val INNERTUBE_KEY_REGEX = Regex("\"INNERTUBE_API_KEY\"\\s*:\\s*\"([A-Za-z0-9_-]{20,80})\"")
        private val VTT_INLINE_TAG_REGEX = Regex("<[^>]*>")
        private val VTT_TIMESTAMP_REGEX = Regex("(?:\\d{1,3}:)?\\d{2}:\\d{2}[.,]\\d{3}")

        fun extractInnertubeApiKey(html: String): String? =
            INNERTUBE_KEY_REGEX.find(html)?.groupValues?.getOrNull(1)

        fun validateTrackUrl(url: String) {
            val uri = URI(url)
            val host = uri.host?.lowercase(Locale.US).orEmpty()
            require(uri.scheme == "https" && (host == "youtube.com" || host.endsWith(".youtube.com") || host.endsWith(".googlevideo.com"))) {
                "Unexpected caption track host"
            }
        }

        fun setFormatParam(url: String, format: String): String {
            return if (Regex("([?&])fmt=[^&]*").containsMatchIn(url)) {
                url.replace(Regex("([?&])fmt=[^&]*"), "$1fmt=$format")
            } else {
                val sep = if ('?' in url) '&' else '?'
                "$url${sep}fmt=$format"
            }
        }

        fun parseCaptionTracks(playerJson: String): List<YouTubeCaptionTrack> {
            val root = runCatching { JSONObject(playerJson) }.getOrNull() ?: return emptyList()
            val tracks = root.optJSONObject("captions")
                ?.optJSONObject("playerCaptionsTracklistRenderer")
                ?.optJSONArray("captionTracks")
                ?: return emptyList()
            val result = mutableListOf<YouTubeCaptionTrack>()
            val seen = mutableSetOf<String>()
            for (i in 0 until tracks.length()) {
                val item = tracks.optJSONObject(i) ?: continue
                val rawUrl = item.optString("baseUrl").replace("\\u0026", "&").trim()
                if (rawUrl.isBlank() || runCatching { validateTrackUrl(rawUrl) }.isFailure) continue
                val lang = item.optString("languageCode").ifBlank { "und" }
                val isAsr = item.optString("kind") == "asr"
                val label = extractTrackName(item.optJSONObject("name"), lang, isAsr)
                val dedupeKey = "$lang|$isAsr"
                if (seen.add(dedupeKey)) {
                    result.add(YouTubeCaptionTrack(lang, label, rawUrl, isAsr))
                }
            }
            return result
        }

        private fun extractTrackName(nameObj: JSONObject?, lang: String, isAsr: Boolean): String {
            val simple = nameObj?.optString("simpleText").orEmpty().trim()
            if (simple.isNotBlank()) return simple
            val runs = nameObj?.optJSONArray("runs")
            if (runs != null) {
                val joined = (0 until runs.length()).joinToString("") { runs.optJSONObject(it)?.optString("text").orEmpty() }.trim()
                if (joined.isNotBlank()) return joined
            }
            return if (isAsr) "$lang (auto-generated)" else lang
        }

        fun choosePreferredTrack(
            tracks: List<YouTubeCaptionTrack>,
            preferredLanguages: List<String> = listOf(Locale.getDefault().language, "en", "ar")
        ): YouTubeCaptionTrack? {
            if (tracks.isEmpty()) return null
            val normalizedPrefs = preferredLanguages.map { it.lowercase(Locale.US) }.filter { it.isNotBlank() }.distinct()
            for (pref in normalizedPrefs) {
                tracks.firstOrNull { !it.isAutoGenerated && it.languageCode.lowercase(Locale.US).startsWith(pref) }?.let { return it }
            }
            tracks.firstOrNull { !it.isAutoGenerated }?.let { return it }
            for (pref in normalizedPrefs) {
                tracks.firstOrNull { it.languageCode.lowercase(Locale.US).startsWith(pref) }?.let { return it }
            }
            return tracks.first()
        }

        fun json3ToVtt(jsonString: String): String {
            val root = JSONObject(jsonString)
            val events = root.optJSONArray("events") ?: JSONArray()
            val sb = StringBuilder("WEBVTT\n\n")
            var cueCount = 0
            var lastText = ""
            for (i in 0 until events.length()) {
                val event = events.optJSONObject(i) ?: continue
                val segs = event.optJSONArray("segs") ?: continue
                val rawText = (0 until segs.length())
                    .joinToString("") { segs.optJSONObject(it)?.optString("utf8").orEmpty() }
                    .replace('\r', ' ')
                    .replace('\n', ' ')
                    .replace(Regex("\\s+"), " ")
                    .trim()
                if (rawText.isBlank() || rawText == lastText) continue
                val startMs = event.optLong("tStartMs", -1L)
                if (startMs < 0L) continue
                val durationMs = event.optLong("dDurationMs", 0L).let { if (it > 0L) it else 2500L }
                val endMs = startMs + durationMs
                val cue = "${formatVttTimestamp(startMs)} --> ${formatVttTimestamp(endMs)}\n$rawText\n\n"
                if (sb.length + cue.length > 950_000) break
                sb.append(cue)
                lastText = rawText
                cueCount++
            }
            return if (cueCount > 0) sb.toString() else ""
        }

        fun cleanWebVtt(rawVtt: String): String {
            val normalized = rawVtt.replace("\r\n", "\n").replace('\r', '\n').removePrefix("\uFEFF")
            val blocks = normalized.split(Regex("\n\\s*\n"))
            val sb = StringBuilder("WEBVTT\n\n")
            val recentLines = ArrayDeque<String>()
            var cueCount = 0
            for (block in blocks) {
                val lines = block.lines()
                val timeIndex = lines.indexOfFirst { "-->" in it }
                if (timeIndex < 0) continue
                val times = VTT_TIMESTAMP_REGEX.findAll(lines[timeIndex]).toList()
                if (times.size != 2) continue
                val cleanedLines = lines.drop(timeIndex + 1)
                    .map { it.replace(VTT_INLINE_TAG_REGEX, "").replace(Regex("\\s+"), " ").trim() }
                    .filter { it.isNotBlank() && it !in recentLines }
                if (cleanedLines.isEmpty()) continue
                val text = cleanedLines.joinToString("\n")
                val timeHeader = "${times[0].value.replace(',', '.')} --> ${times[1].value.replace(',', '.')}"
                val entry = "$timeHeader\n$text\n\n"
                if (sb.length + entry.length > 950_000) break
                sb.append(entry)
                cleanedLines.forEach { line ->
                    recentLines.addLast(line)
                    if (recentLines.size > 4) recentLines.removeFirst()
                }
                cueCount++
            }
            return if (cueCount > 0) sb.toString() else ""
        }

        fun formatVttTimestamp(ms: Long): String {
            val safe = ms.coerceAtLeast(0L)
            val totalSecs = safe / 1000L
            val millis = safe % 1000L
            val hours = totalSecs / 3600L
            val mins = (totalSecs % 3600L) / 60L
            val secs = totalSecs % 60L
            return String.format(Locale.US, "%02d:%02d:%02d.%03d", hours, mins, secs, millis)
        }
    }
}
